classdef HTMLTestSupport
    methods (Static)
        function frame = frame()
            data = table( ...
                ["Model A"; "Model A"; "Model A"; "Model B"; "Model B"; "Model C"], ...
                ["Scenario A"; "Scenario A"; "Scenario A"; "Scenario B"; "Scenario B"; "Scenario C"], ...
                ["Emissions|CO2"; "Emissions|CO2"; "Emissions|CO2"; "Emissions|CO2"; "Emissions|CO2"; "Temperature"], ...
                repmat("World",6,1), [repmat("Mt/yr",5,1); "C"], ...
                [101;101;101;202;202;303], ones(6,1), ...
                [2020;2030;2040;2020;2040;2020], [10;NaN;-2;8;4;1.5], ...
                VariableNames=["Model","Scenario","Variable","Region","Unit","RunId","Version","Year","Value"]);
            frame = iam.IAMFrame(data);
        end

        function [environment, connection] = environment()
            frame = HTMLTestSupport.frame();
            refs = struct( ...
                "models", table((1:3)', ["Model A";"Model B";"Model C"], VariableNames=["ID","Name"]), ...
                "scenarios", table((1:3)', ["Scenario A";"Scenario B";"Scenario C"], VariableNames=["ID","Name"]), ...
                "variables", table([1;2], ["Emissions|CO2";"Temperature"], [1;2], ["Mt/yr";"C"], ...
                    VariableNames=["ID","Name","Unit ID","Unit"]), ...
                "regions", table(1, "World", "common", "World", "", ...
                    VariableNames=["ID","Name","Hyerarchy","Parent","Synonyms"]));
            runs = table(["Model A";"Model B";"Model C"], ...
                ["Scenario A";"Scenario B";"Scenario C"], [101;202;303], ones(3,1), ...
                VariableNames=["model","scenario","run_id","version"]);
            connection = HTMLAppConnection(Refs=refs, Runs=runs, ...
                BulkDataResponse=frame.toTimeseries());
            environment = iam.IAMEnvironment(connection);
        end
    end
end
